MODELS = ["anthropic/claude-haiku-4-5", "openai/gpt-5-nano-2025-08-07", "gemini/gemini-2.5-flash-lite"]


def load_stage1_responses(filepath):
    """Load stage 1 responses from JSON file."""
    with open(filepath, "r", encoding="utf-8") as f:
        return json.load(f)


def evaluate_subcategory(evaluating_model, parent_category, subcategory_data):
    """Evaluate a single subcategory using the specified model (anonymously)."""
    # Format subcategory as JSON string for the prompt
    subcategory_json = json.dumps(subcategory_data, indent=2, ensure_ascii=False)
    
    # Create user prompt with subcategory (no model name passed)
    user_prompt = STAGE_2_USER_PROMPT.format(
        parent_category=parent_category,
        subcategory_json=subcategory_json
    )
    
    print(f"  Evaluating with {evaluating_model}...")
    evaluation_response = call_model(
        model_name=evaluating_model,
        system_prompt=STAGE_2_SYSTEM_PROMPT,
        user_prompt=user_prompt
    )
    
    try:
        if isinstance(evaluation_response, str):
            cleaned_response = clean_json_response(evaluation_response)
            parsed_evaluation = json.loads(cleaned_response)
        else:
            parsed_evaluation = evaluation_response
    except json.JSONDecodeError as e:
        print(f'    JSON parsing failed for {evaluating_model}: {e}')
        parsed_evaluation = {"error": str(e), "raw_response": evaluation_response}
    
    return parsed_evaluation


def main():
    # TODO modify this to auto-detect the latest
    stage1_file = "data_generation/stage1_responses_20251228_141046.json"
    
    if not os.path.exists(stage1_file):
        print(f"Error: file not found: {stage1_file}")
        return
    stage1_responses = load_stage1_responses(stage1_file)
    all_evaluations = []
    
    # For each model's response
    for generating_model_response in stage1_responses:
        generating_model = generating_model_response["model"]
        parent_category = generating_model_response["parent_category"]
        subcategories = generating_model_response["response"].get("subcategories", [])
        print(subcategories)
        
        print(f"\nProcessing subcategories from {generating_model} ({len(subcategories)} subcategories)")
        
        # For each subcategory generated by this model
        for subcategory_idx, subcategory in enumerate(subcategories):
            print(f"  Subcategory {subcategory_idx + 1}: {subcategory.get('name', 'Unknown')}")
            
            # Each evaluating model evaluates this subcategory
            for evaluating_model in MODELS:
                evaluation_result = evaluate_subcategory(
                    evaluating_model=evaluating_model,
                    parent_category=parent_category,
                    subcategory_data=subcategory
                )
                
                # Store evaluation with all required fields
                evaluation_record = {
                    "content_evaluated": subcategory,  # The full subcategory content
                    "score": evaluation_result.get("score"),
                    "reasoning": evaluation_result.get("reasoning"),
                    "strengths": evaluation_result.get("strengths", []),
                    "weaknesses": evaluation_result.get("weaknesses", []),
                    "model_generated": generating_model,  # Model that generated the subcategory
                    "model_evaluated": evaluating_model,  # Model that evaluated it
                    "parent_category": parent_category,
                    "subcategory_name": subcategory.get("name", "Unknown")
                }
                
                all_evaluations.append(evaluation_record)
    
    output_filename = f"stage2_evaluations_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json"
    output_path = os.path.join("data_generation", output_filename)
    
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(all_evaluations, f, indent=2, ensure_ascii=False)

if __name__ == "__main__":
    main()
